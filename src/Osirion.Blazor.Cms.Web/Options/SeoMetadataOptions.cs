using Osirion.Blazor.Cms.Web.Components;

namespace Osirion.Blazor.Cms.Web.Options;

/// <summary>
/// Configuration options for SEO metadata rendering across the site.
/// These settings provide default values that can be overridden on a per-page basis.
/// </summary>
public class SeoMetadataOptions
{
    /// <summary>
    /// Gets or sets the site name used in Open Graph and general metadata.
    /// If not set, will be extracted from the domain name.
    /// </summary>
    public string? SiteName { get; set; }

    /// <summary>
    /// Gets or sets the site's public address, such as <c>https://example.com</c>. When set, the canonical URL,
    /// <c>og:url</c> and the addresses in structured data use it with the page's path, whatever host served the
    /// request (a proxy, a preview host, a second domain). Only an absolute <c>http</c> or <c>https</c> address is
    /// used; without one they follow the request, as before.
    /// </summary>
    public string? SiteUrl { get; set; }

    /// <summary>
    /// Gets or sets the site-wide description. <c>MapOsirionFeeds</c> uses it as the feed description when the feed
    /// options set none. <c>SeoMetadataRenderer</c> writes no tag and no structured data from it.
    /// </summary>
    public string? SiteDescription { get; set; }

    /// <summary>
    /// Gets or sets the URL to the site logo (recommended: square format, min 112x112px).
    /// </summary>
    public string? SiteLogoUrl { get; set; }

    /// <summary>
    /// Gets or sets the Twitter handle for the site (e.g., "@yoursite").
    /// </summary>
    public string? TwitterSite { get; set; }

    /// <summary>
    /// Gets or sets the default Twitter handle for content creators (e.g., "@author").
    /// </summary>
    public string? TwitterCreator { get; set; }

    /// <summary>
    /// Gets or sets the Facebook App ID for Facebook Insights.
    /// </summary>
    public string? FacebookAppId { get; set; }

    /// <summary>
    /// Gets or sets whether to allow AI systems to discover and index content by default.
    /// </summary>
    public bool AllowAiDiscovery { get; set; } = true;

    /// <summary>
    /// Gets or sets whether to allow AI systems to use content for training purposes by default.
    /// </summary>
    public bool AllowAiTraining { get; set; } = true;

    /// <summary>
    /// Gets or sets whether to allow traditional search engines to index content by default.
    /// </summary>
    public bool AllowSearchIndexing { get; set; } = true;

    /// <summary>
    /// Gets or sets whether to enable Generative Engine Optimization (GEO) meta tags by default.
    /// </summary>
    public bool EnableGeoOptimization { get; set; } = true;

    /// <summary>
    /// Gets or sets whether to enable Answer Engine Optimization (AEO) structured answers by default.
    /// </summary>
    public bool EnableAeoOptimization { get; set; } = true;

    /// <summary>
    /// Gets or sets whether the viewport, theme-color and mobile web app meta tags are emitted by default.
    /// Off by default because the host document normally owns them.
    /// </summary>
    public bool EmitMobileMetaTags { get; set; }

    /// <summary>
    /// Gets or sets whether FAQ structured data and answer meta tags derived from titles and descriptions are
    /// generated by default (also requires <see cref="EnableAeoOptimization"/>). Off by default.
    /// </summary>
    public bool EnableGeneratedFaq { get; set; }

    /// <summary>
    /// Gets or sets whether to generate multiple schema types when applicable by default.
    /// </summary>
    public bool GenerateMultipleSchemas { get; set; } = true;

    /// <summary>
    /// Gets or sets the default fallback image URL when content has no featured image.
    /// </summary>
    public string? DefaultImageUrl { get; set; }

    /// <summary>
    /// Gets or sets the default image width for Open Graph (recommended: 1200px).
    /// </summary>
    public int DefaultImageWidth { get; set; } = 1200;

    /// <summary>
    /// Gets or sets the default image height for Open Graph (recommended: 630px).
    /// </summary>
    public int DefaultImageHeight { get; set; } = 630;

    /// <summary>
    /// Gets or sets the organization name for structured data.
    /// </summary>
    public string? OrganizationName { get; set; }

    /// <summary>
    /// Gets or sets a page that identifies the author, such as <c>/about</c>, named as the author's <c>url</c> in
    /// structured data. It is meant for a site with one author: every article and every posting in a list names it.
    /// Without one the author is named alone.
    /// </summary>
    public string? AuthorUrl { get; set; }

    /// <summary>
    /// Gets or sets the default text label for the home breadcrumb.
    /// </summary>
    public string BreadcrumbHomeText { get; set; } = "Home";

    /// <summary>
    /// Gets or sets the referrer policy written as <c>&lt;meta name="referrer"&gt;</c> on every page, one of the
    /// policy tokens of the Referrer Policy specification, such as <c>strict-origin-when-cross-origin</c>. Empty by
    /// default, so no tag is written and the site's <c>Referrer-Policy</c> response header (or the browser default,
    /// <c>strict-origin-when-cross-origin</c>) applies: a referrer meta tag replaces the header's policy for the whole
    /// document. A value that is not a policy token writes nothing.
    /// </summary>
    public string? ReferrerPolicy { get; set; }

    /// <summary>
    /// Gets or sets the default schema types to generate for content pages.
    /// </summary>
    public SchemaType[]? DefaultSchemaTypes { get; set; }

    /// <summary>
    /// Gets or sets meta elements written on every page, as name and content pairs, such as
    /// <c>ai-content-declaration</c>. The renderer makes no such declaration on its own. A front matter
    /// <c>meta_tags</c> entry with the same name replaces the value for that page. Names follow the rules of
    /// <c>meta_tags</c>: a letter, then letters, digits and <c>- _ . :</c>, and not a name the renderer writes itself.
    /// </summary>
    public Dictionary<string, string> AdditionalMetaTags { get; set; } = [];

    /// <summary>
    /// Gets or sets whether the site's own structured data is written: the home page (the site root, or a culture's
    /// root on a site with locale routing) gets a schema.org <c>WebSite</c> (<c>@id</c> <c>{SiteUrl}/#website</c>) and
    /// an <c>Organization</c> (<c>@id</c> <c>{SiteUrl}/#organization</c>, from <see cref="OrganizationName"/> or
    /// <see cref="SiteName"/>, <see cref="SiteLogoUrl"/> and <see cref="SameAs"/>), and every page names them by
    /// <c>@id</c>: its <c>publisher</c> is the organization, and a web page is <c>isPartOf</c> the web site. Off by
    /// default, which writes the structured data as before. Set <see cref="SiteUrl"/> with it, so the ids name the
    /// public address.
    /// </summary>
    public bool EnableSiteSchemas { get; set; }

    /// <summary>
    /// Gets or sets the organization's profiles on other sites, such as its social accounts, written as the
    /// <c>sameAs</c> of the site's <c>Organization</c> (<see cref="EnableSiteSchemas"/>). Only absolute <c>http</c> and
    /// <c>https</c> addresses are written.
    /// </summary>
    public List<string> SameAs { get; set; } = [];

    /// <summary>
    /// Gets or sets the address of the site's search results with <c>{search_term_string}</c> where the query goes,
    /// such as <c>/search?q={search_term_string}</c>, written as the <c>SearchAction</c> of the site's <c>WebSite</c>
    /// (<see cref="EnableSiteSchemas"/>). A path is made absolute with the site address. Without it, or without the
    /// placeholder, no search action is written.
    /// </summary>
    public string? SearchUrlTemplate { get; set; }
}
